#!/usr/bin/env node
// =============================================================================
// build_demo_site.mjs — builds demo/demo-data.js for demo.poolsideapp.com (BG9)
// =============================================================================
// The demo club runs in the visitor's own browser: sw.js, on the demo host,
// answers every Supabase call from this file, so nothing is ever sent and no
// calls are used. This joins data.mjs (the video's club) and site_data.mjs
// (the rest of the screens) into one plain script, and adds what's worked out
// from the app's own code: the emails on Settings → Emails with a preview of
// each, and the board positions.
//
// Run after changing data.mjs, site_data.mjs or the emails:
//   node scripts/demo_video/build_demo_site.mjs
// test_demo_site.mjs fails if demo/demo-data.js is out of date.
// =============================================================================

import { readFileSync, writeFileSync } from 'node:fs';
import { importTs } from '../lib/importts.mjs';

const root = new URL('../../', import.meta.url);
const read = rel => readFileSync(new URL(rel, root), 'utf8');

// The email module reads Deno.env through send_email.ts; nothing is sent here.
globalThis.Deno = globalThis.Deno || { env: { get: () => undefined } };

export async function buildPre() {
  const et = await importTs(new URL('supabase/functions/_shared/email_template.ts', root));
  const pos = await importTs(new URL('supabase/functions/_shared/positions.ts', root));
  const sample = {
    tenant_name: 'Maple Grove Swim Club', primary_name: 'Jamie Rivera', family_name: 'Rivera Family', member_name: 'Sofia Rivera', member_role: 'teen',
    tier_label: 'Family', amount: '$550.00', sequence: '2', next_amount: '$200.00', next_due_date: 'Thursday, July 1', due_date: 'Thursday, July 1', days_until: '3',
    sign_in_link: 'https://demo.poolsideapp.com/m/', club_url: 'https://demo.poolsideapp.com', renew_link: 'https://demo.poolsideapp.com/m/renew.html',
    manage_url: 'https://demo.poolsideapp.com/m/#plan', member_url: 'https://demo.poolsideapp.com/m/#parties', season: '2027', charge_date: 'December 15, 2026',
    party_title: "Leo's 9th birthday", party_date: 'Saturday, June 19, 2027', party_time: '4:00 PM', price: '$150.00', hold_days: '2',
    venmo_handle: 'maplegroveswim', venmo_link: 'https://venmo.com/maplegroveswim', venmo_code: 'K7Q2', reason: 'the card was declined four times',
    paid: '$350.00', owed: '$200.00', fee: '$50.00', total: '$250.00', paid_by: 'card', admin_notes: '',
    message: "It's time to sign up for the 2027 season. Your family's details are already filled in.",
  };
  const emails = et.EMAIL_REGISTRY.map(d => ({
    key: d.key, label: d.label, when: d.when, section: d.section, adds: d.adds, placeholders: d.placeholders,
    default_subject: d.default_subject, default_message: d.default_message,
    variants: (d.variants ?? []).map(v => ({ id: v.id, label: v.label })), override: null,
  }));
  const previews = {};
  for (const d of et.EMAIL_REGISTRY) {
    for (const v of (d.variants?.length ? d.variants : [{ id: '' }])) {
      previews[`${d.key}|${v.id}`] = et.renderPreview(d.key, null, null, sample, v.id || null);
    }
  }
  return {
    emails, previews, emailSections: et.EMAIL_SECTIONS, emailAliases: et.EMAIL_ALIASES,
    positions: pos.STARTER_POSITIONS,
    notices: Object.fromEntries(Object.entries(pos.NOTICES).map(([k, v]) => [k, v.label])),
    screens: pos.SCREENS,
  };
}

/** One plain script: the two data modules, without import/export. */
export function bundleSource() {
  const strip = s => s
    .replace(/^import [^\n]*\n/gm, '')
    .replace(/^export (const|function|let) /gm, '$1 ');
  return [read('scripts/demo_video/data.mjs'), read('scripts/demo_video/site_data.mjs')].map(strip).join('\n');
}

export async function buildDemoData() {
  const pre = await buildPre();
  return `// GENERATED by scripts/demo_video/build_demo_site.mjs — do not edit by hand.
// The demo club (PLAN.md BG9): made-up Maple Grove, answered in the browser.
self.DEMO_PRE = ${JSON.stringify(pre)};
(function () {
${bundleSource()}
self.DemoSite = { siteRespond, weather, WOULD, DEMO_NOW, CLUB };
})();
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = await buildDemoData();
  writeFileSync(new URL('demo/demo-data.js', root), out);
  console.log(`demo/demo-data.js: ${(out.length / 1024).toFixed(0)} KB`);
}
