"""
Poolside gate bridge — runs on the club's on-site Windows PC.

Checks in with the Poolside cloud for gate-unlock commands and runs the
proven 2-step HTTP recipe against the panel on the club's LAN. Since 1.2
(PLAN.md AK) the board can open the other wired doors too: those go
straight to their controller with uhppoted's open_door (pip install
uhppoted, as for the read-only keyfob check); the front gate keeps the
HTTP recipe. Since 1.4 (PLAN.md AS4) it also puts Poolside's keyfobs on the
controllers when the board asks ("Sync keyfobs now": read first, then
send exactly the changes), card by card, so the doors never go down.
Since 1.3 (PLAN.md AO) a check-in is held up to 2 minutes
(about 720 calls a day) and the cloud says how long to ask for next time,
so that can change without touching this PC. Since 1.1
(PLAN.md AA) each check-in asks the cloud to wait up to WAIT_SEC for an
unlock, so the bridge calls about once every 20 seconds instead of every
1.5 (which used up the free Supabase plan in September 2026), and the gate
still opens within a second of a tap. Translated from the field-tested Bishop Estates v0.4 bridge,
re-pointed at Poolside's per-bridge auth model (X-Bridge-Id +
X-Bridge-Secret) instead of using the service-role key.

Auth posture:
  - The bridge knows ONLY its own bridge_id + bridge_secret.
  - If the Pi is stolen, the attacker can only fire unlock commands at this
    one tenant's panel. They can't read anyone's data.
  - The bridge_secret is generated by clicking "Rotate bridge secret" in
    the Poolside admin → Settings → 🔐 Remote keyfob access card. The
    plaintext is shown ONCE; if you lose it, rotate again.

Config: see .env.example. Run as a Windows service via nssm — see README.md.
"""
from __future__ import annotations

import json
import logging
import os
import sys
import time
from datetime import datetime, timezone
from urllib.parse import urlencode

import requests
from dotenv import load_dotenv

# Load .env from the script's own directory (so the nssm service finds it
# regardless of where it was started from).
_HERE = os.path.dirname(os.path.abspath(__file__))
load_dotenv(os.path.join(_HERE, ".env"))

LOG = logging.getLogger("poolside_gate_bridge")
_log_path = os.path.join(_HERE, "bridge.log")
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s %(levelname)s %(message)s",
    handlers=[
        logging.StreamHandler(sys.stdout),
        logging.FileHandler(_log_path, encoding="utf-8"),
    ],
)

# ── Required config ────────────────────────────────────────────────────
SUPABASE_URL  = os.environ["SUPABASE_URL"].rstrip("/")
BRIDGE_ID     = os.environ["BRIDGE_ID"]
BRIDGE_SECRET = os.environ["BRIDGE_SECRET"]

# ── Tunables (defaults work for typical small clubs) ───────────────────
# WAIT_SEC: how long to ask the cloud to hold the first check-in. After that
#   the cloud says (next_wait, PLAN.md AO2), kept between 5 and 130 seconds.
# MIN_LOOP_SEC: never call more often than this, even if the cloud answers at
#   once (an older cloud, or a hiccup). The guard against September's bill.
# POLL_SEC: the first wait after an error; it doubles up to MAX_BACKOFF_SEC.
WAIT_SEC          = int(os.environ.get("WAIT_SEC", "120"))
WAIT_MIN_SEC      = 5
WAIT_MAX_SEC      = 130   # Supabase ends any call at 150 s
MIN_LOOP_SEC      = float(os.environ.get("MIN_LOOP_SEC", "5"))
POLL_SEC          = max(1.0, float(os.environ.get("POLL_SEC", "5")))
MAX_BACKOFF_SEC   = 60.0
STALE_COMMAND_SEC = int(os.environ.get("STALE_COMMAND_SEC", "60"))
BRIDGE_VERSION    = "1.4.0-poolside"

# ── Cloud endpoint ─────────────────────────────────────────────────────
CLOUD_URL = f"{SUPABASE_URL}/functions/v1/gate_bridge"
CLOUD_HEADERS = {
    "Content-Type": "application/json",
    "X-Bridge-Id": BRIDGE_ID,
    "X-Bridge-Secret": BRIDGE_SECRET,
}


# =============================================================================
# Panel adapter — the proven 2-step POST recipe.
# =============================================================================
# This block is copied verbatim from Bishop Estates' battle-tested code. Do
# not "improve" it — every quirk (the magic logId, the requests.Session for
# cookie persistence, the explicit form encoding) was earned through hours
# of troubleshooting against the real MENGQI-CONTROL HXC-7000 panel.
#
# Panel firmware tested: 2.4.7 (Bishop Estates).
# =============================================================================

PANEL_LOG_ID = "20101222"  # Panel-side magic constant — not a date, not random.

def unlock_panel(host: str, user: str, pwd: str, door: int = 1) -> tuple[bool, str]:
    """Open the gate. Returns (ok, detail). Never raises."""
    if not host:
        return False, "panel host not configured in Poolside admin"
    s = requests.Session()
    base = f"http://{host}"
    try:
        # Step 1 — login. Sets a session cookie on the requests.Session.
        # Panel rejects step 2 without this cookie.
        r1 = s.post(
            f"{base}/ACT_ID_1",
            data=urlencode({"username": user, "pwd": pwd, "logId": PANEL_LOG_ID}),
            headers={"Content-Type": "application/x-www-form-urlencoded"},
            timeout=5,
        )
        if r1.status_code != 200:
            return False, f"login HTTP {r1.status_code}"

        # Step 2 — actually open the gate. UNCLOSE1 = door 1; the value is
        # a label that shows up in the panel's local audit log.
        r2 = s.post(
            f"{base}/ACT_ID_701",
            data=urlencode({f"UNCLOSE{door}": f"Remote Open #{door} Door Main Gate"}),
            headers={"Content-Type": "application/x-www-form-urlencoded"},
            timeout=5,
        )
        if r2.status_code != 200:
            return False, f"unlock HTTP {r2.status_code}"
        return True, "panel returned 200"
    except requests.RequestException as e:
        return False, f"panel unreachable: {e}"


# =============================================================================
# Other doors (PLAN.md AK) — straight to the door's controller.
# =============================================================================
# The two keyfob controllers speak the UHPPOTE protocol (64-byte UDP packets
# on port 60000; docs/keyfob-panels.md). uhppoted's open_door asks one to
# release one door, exactly like a keyfob at that door. No password: the
# controllers only answer on the pool's own network.
# =============================================================================

def _uhppote_client():
    from uhppoted.uhppote import Uhppote  # pip install uhppoted (in this venv)
    return Uhppote(bind="0.0.0.0", broadcast="255.255.255.255:60000", listen="0.0.0.0:60001")


def open_door_udp(controller, address, door, make_client=None) -> tuple[bool, str]:
    """Open one door on one controller. Returns (ok, detail). Never raises."""
    try:
        controller, door = int(controller), int(door)
    except (TypeError, ValueError):
        return False, "door details missing"
    if controller <= 0 or not 1 <= door <= 4 or not address:
        return False, f"bad door details (controller {controller}, door {door})"
    try:
        client = (make_client or _uhppote_client)()
    except ImportError:
        return False, "uhppoted not installed on this PC (pip install uhppoted)"
    try:
        reply = client.open_door((controller, str(address), "udp"), door)
    except Exception as e:  # a timeout, a closed network, a bad reply
        return False, f"controller unreachable: {e}"
    if reply is None:
        return False, "no answer from the controller"
    if not getattr(reply, "opened", False):
        return False, "the controller said no"
    return True, f"controller {controller} opened door {door}"


# =============================================================================
# Keyfob sync (PLAN.md AS4) — read what the controllers hold, write changes.
# =============================================================================
# A "check" job lists the cards and time windows Poolside manages; the
# bridge reads each one (get_card, get_time_profile) and reports it. A
# "send" job lists the writes Poolside worked out: put a card (dates, each
# door's 0/1/window, the keypad PIN kept), delete a card, set a window. Each
# is read back so the board sees what's actually live. Cards Poolside doesn't
# manage are never in a job. A read that fails is reported as an error, never
# as "missing", so Poolside never re-adds cards because a controller blinked.
# =============================================================================

import datetime as _dt

def _d(s):
    return _dt.date.fromisoformat(str(s)[:10])

def _t(s):
    h, m = str(s)[:5].split(":")
    return _dt.time(int(h), int(m))

def _hhmm(v):
    return v.strftime("%H:%M") if v is not None else None

def _card_have(rec):
    if rec is None or not getattr(rec, "card_number", 0):
        return None
    return {"from": rec.start_date.isoformat(), "to": rec.end_date.isoformat(),
            "doors": [int(rec.door_1), int(rec.door_2), int(rec.door_3), int(rec.door_4)], "pin": int(getattr(rec, "pin", 0) or 0)}

def _profile_have(rec):
    if rec is None or not getattr(rec, "profile_id", 0):
        return None
    days = [bool(getattr(rec, d)) for d in ("monday", "tuesday", "wednesday", "thursday", "friday", "saturday", "sunday")]
    return {"from": rec.start_date.isoformat(), "to": rec.end_date.isoformat(), "days": days,
            "start": _hhmm(rec.segment_1_start), "end": _hhmm(rec.segment_1_end)}

def run_sync(job, make_client=None):
    """Do a sync job. Returns (result, error). Never raises."""
    try:
        client = (make_client or _uhppote_client)()
    except ImportError:
        return None, "uhppoted not installed on this PC (pip install uhppoted)"
    except Exception as e:
        return None, f"couldn't start uhppoted: {e}"
    plan = job.get("plan") or {}
    addr = {int(c["serial"]): str(c["address"]) for c in plan.get("controllers", [])}
    ctrl = lambda serial: (int(serial), addr.get(int(serial)), "udp")
    # A controller that fails twice in a row is skipped for the rest of the
    # job (each try waits 2.5 s), and reported as not answering.
    fails, dead = {}, set()
    def attempt(serial, fn):
        if serial in dead:
            raise RuntimeError("controller not answering")
        try:
            v = fn()
            fails[serial] = 0
            return v
        except Exception:
            fails[serial] = fails.get(serial, 0) + 1
            if fails[serial] >= 2:
                dead.add(serial)
            raise
    if job.get("kind") == "check":
        cards, profiles = [], []
        for c in plan.get("cards", []):
            entry = {"card": c["card"], "controller": c["controller"]}
            try:
                entry["have"] = _card_have(attempt(int(c["controller"]), lambda: client.get_card(ctrl(c["controller"]), int(c["card"]))))
            except Exception as e:
                entry["have"], entry["error"] = None, str(e)[:200]
            cards.append(entry)
        for p in plan.get("profiles", []):
            entry = {"controller": p["controller"], "id": p["id"]}
            try:
                entry["have"] = _profile_have(attempt(int(p["controller"]), lambda: client.get_time_profile(ctrl(p["controller"]), int(p["id"]))))
            except Exception as e:
                entry["have"], entry["error"] = None, str(e)[:200]
            profiles.append(entry)
        return {"cards": cards, "profiles": profiles}, None
    done = []
    for op in plan.get("ops", []):
        out = dict(op)
        try:
            if int(op["controller"]) in dead:
                raise RuntimeError("controller not answering")
            c = ctrl(op["controller"])
            if op["op"] == "put":
                d = [int(x) for x in op["doors"]] + [0, 0, 0, 0]
                r = client.put_card(c, int(op["card"]), _d(op["from"]), _d(op["to"]), d[0], d[1], d[2], d[3], int(op.get("pin") or 0))
                out["ok"] = bool(getattr(r, "stored", False))
                back = _card_have(client.get_card(c, int(op["card"])))
                out["live"] = bool(back and back["from"] == op["from"] and back["to"] == op["to"] and back["doors"] == d[:4])
            elif op["op"] == "delete":
                r = client.delete_card(c, int(op["card"]))
                out["ok"] = bool(getattr(r, "deleted", False))
                out["live"] = _card_have(client.get_card(c, int(op["card"]))) is None
            elif op["op"] == "profile":
                days = list(op["days"])
                s1, e1 = _t(op["start"]), _t(op["end"])
                s2 = e2 = _dt.time(0, 0)
                if e1 <= s1:                       # overnight: two segments
                    s1, e1, s2, e2 = _t(op["start"]), _dt.time(23, 59), _dt.time(0, 0), _t(op["end"])
                r = client.set_time_profile(c, int(op["id"]), _d(op["from"]), _d(op["to"]), *days,
                                            s1, e1, s2, e2, _dt.time(0, 0), _dt.time(0, 0), 0)
                out["ok"] = bool(getattr(r, "stored", False))
                back = _profile_have(client.get_time_profile(c, int(op["id"])))
                out["live"] = bool(back and back["from"] == op["from"] and back["to"] == op["to"] and back["days"] == days)
            else:
                out["ok"], out["error"] = False, "unknown change"
            fails[int(op["controller"])] = 0
        except Exception as e:
            out["ok"], out["live"], out["error"] = False, False, str(e)[:200]
            fails[int(op["controller"])] = fails.get(int(op["controller"]), 0) + 1
            if fails[int(op["controller"])] >= 2:
                dead.add(int(op["controller"]))
        done.append(out)
    return {"ops": done}, None


# =============================================================================
# Cloud client — talks to Poolside's gate_bridge edge function.
# =============================================================================

_CLOUD = None

def cloud(action: str, **extra) -> tuple[int, dict]:
    """POST to the gate_bridge endpoint. Returns (status_code, body_dict).
    Never raises — returns (0, {error: ...}) on network failure. One kept-
    alive connection, so check-ins don't each pay for a new TLS handshake."""
    global _CLOUD
    if _CLOUD is None:
        _CLOUD = requests.Session()
    body = {"action": action, "version": BRIDGE_VERSION, **extra}
    wait = int(extra.get("wait") or 0)
    try:
        # A held check-in can take its whole wait; leave room before giving up.
        r = _CLOUD.post(CLOUD_URL, headers=CLOUD_HEADERS, data=json.dumps(body), timeout=wait + 15)
        try:
            return r.status_code, r.json()
        except ValueError:
            return r.status_code, {"raw": r.text[:200]}
    except requests.RequestException as e:
        return 0, {"error": str(e)}


# =============================================================================
# Main loop.
# =============================================================================

def is_stale(requested_at_iso: str | None) -> bool:
    """A command is stale if it was queued before the bridge was last alive.
    Without this guard, a bridge that was offline for an hour comes back
    and fires the panel 30 times in rapid succession when it picks up the
    backlog. Stolen from Bishop Estates' hard-won abort_stale_pending."""
    if not requested_at_iso:
        return False
    try:
        # Tolerate trailing 'Z' (Postgres) or +00:00 (newer Postgres versions)
        ts = requested_at_iso.replace("Z", "+00:00")
        when = datetime.fromisoformat(ts)
        age = (datetime.now(timezone.utc) - when).total_seconds()
        return age > STALE_COMMAND_SEC
    except ValueError:
        return False


def run_loop(cloud_fn, sleep_fn, clock_fn, unlock_fn, until: float | None = None, open_fn=None, sync_fn=None) -> None:
    """The check-in loop. Takes its cloud, clock, panel and controllers as
    arguments so it can be tested against a fake (scripts/test_gate_bridge_loop.py).

    Each check-in asks the cloud to wait for an unlock: WAIT_SEC the first
    time, then as long as the cloud says (next_wait). Never more often than
    every MIN_LOOP_SEC, and after an error it waits POLL_SEC, doubling up to
    a minute. No separate heartbeat: every check-in tells the cloud the
    bridge is alive."""
    open_fn = open_fn or open_door_udp
    sync_fn = sync_fn or run_sync
    errors = 0
    wait = max(WAIT_MIN_SEC, min(WAIT_MAX_SEC, WAIT_SEC))
    while until is None or clock_fn() < until:
        started = clock_fn()
        code, resp = cloud_fn("poll", wait=wait)
        if code != 200 and clock_fn() - started >= MIN_LOOP_SEC:
            # A long hold cut short (Supabase ended the call). Not an outage:
            # the cloud was answering, so ask again straight away.
            LOG.info(f"check-in ended early ({code}); asking again")
            errors = 0
            continue
        if code != 200:
            errors += 1
            wait = min(MAX_BACKOFF_SEC, POLL_SEC * (2 ** (errors - 1)))
            LOG.warning(f"poll {code}: {resp.get('error', resp)} (trying again in {wait:.0f}s)")
            sleep_fn(wait)
            continue
        errors = 0
        try:
            wait = max(WAIT_MIN_SEC, min(WAIT_MAX_SEC, int(resp.get("next_wait") or wait)))
        except (TypeError, ValueError):
            pass

        # A keyfob sync (1.4, PLAN.md AS4): handed out only when no door is waiting.
        job = resp.get("sync")
        if job:
            LOG.info(f"Keyfob sync {str(job.get('id'))[:8]}... ({job.get('kind')})")
            result, err = sync_fn(job)
            cloud_fn("sync_done", id=job.get("id"), result=result or {}, error=err)
            LOG.info(f"  → {'failed: ' + err if err else 'done'}")
            continue

        command = resp.get("command")
        if not command:
            # The cloud held the check-in and nothing came. If it answered
            # early (an older cloud), don't call again too soon.
            sleep_fn(max(0.0, MIN_LOOP_SEC - (clock_fn() - started)))
            continue

        cmd_id = command.get("id") or ""
        tenant = resp.get("tenant", {})

        # Stale guard — if we've been offline and the cloud handed us a
        # ten-minute-old request, don't fire it. Mark as 'stale' so the
        # admin sees it in the audit log but the gate stays closed.
        if is_stale(command.get("requested_at")):
            LOG.info(f"Skipping stale command {cmd_id[:8]}... (queued before bridge came online)")
            cloud_fn("complete", unlock_id=cmd_id, result_code="stale",
                     result_detail=f"command older than {STALE_COMMAND_SEC}s when bridge polled")
            continue

        is_test = bool(command.get("is_test"))
        door = command.get("door") or {}
        LOG.info(f"Picked up unlock {cmd_id[:8]}... {door.get('name') or 'front gate'} {'(admin test)' if is_test else ''}")

        if door.get("key") not in (None, "main_gate"):
            # Another door (PLAN.md AK): straight to its controller.
            ok, detail = open_fn(controller=door.get("controller"), address=door.get("address"), door=door.get("door"))
        else:
            # The front gate: the proven recipe.
            ok, detail = unlock_fn(
                host=tenant.get("panel_host") or "",
                user=tenant.get("panel_admin_user") or "admin",
                pwd=tenant.get("panel_admin_password") or "",
            )
        result_code = "ok" if ok else "panel_unreachable" if "unreachable" in detail else "panel_failed"
        cloud_fn("complete", unlock_id=cmd_id, result_code=result_code, result_detail=detail)
        LOG.info(f"  → {result_code}: {detail}")


def main() -> None:
    LOG.info(f"Poolside gate bridge {BRIDGE_VERSION} starting")
    LOG.info(f"  cloud:  {CLOUD_URL}")
    LOG.info(f"  bridge: {BRIDGE_ID}")
    LOG.info(f"  check-ins held up to {WAIT_SEC}s at first (then as the cloud says), never more often than every {MIN_LOOP_SEC:.0f}s")
    try:
        _uhppote_client()
        LOG.info("  other doors: ready (uhppoted installed)")
    except ImportError:
        LOG.warning("  other doors: uhppoted isn't installed, so only the front gate will open (pip install uhppoted)")
    except Exception as e:
        LOG.warning(f"  other doors: uhppoted didn't start ({e})")

    # First contact — also serves as a sanity check that creds are right.
    # 401 is fatal: bridge_id/secret are wrong, no point burning CPU on a
    # cred that will never start working. 403 is NON-fatal as of 2026-05-23:
    # it means the platform admin hasn't flipped this tenant to 'active'
    # yet, but they probably will soon — the bridge keeps checking in (with
    # back-off) and picks up the moment activation happens.
    code, resp = cloud("heartbeat")
    if code == 401:
        LOG.error("Auth failed (401). Check BRIDGE_ID and BRIDGE_SECRET in .env.")
        LOG.error("If your secret was lost, rotate it in Poolside admin → Settings → 🔐 Remote keyfob access.")
        sys.exit(2)
    if code == 403:
        LOG.warning("Tenant gate add-on is not 'active' yet — staying alive and checking in.")
        LOG.warning("Once the platform admin clicks '🟢 Activate gate' in /admin/gate-integrations.html,")
        LOG.warning("the next check-in succeeds automatically. No restart needed.")
    elif code != 200:
        LOG.warning(f"First heartbeat returned {code}: {resp.get('error', resp)}. Will keep trying...")
    else:
        LOG.info("First heartbeat ok — credentials accepted.")

    while True:
        try:
            run_loop(cloud, time.sleep, time.time, unlock_panel)
        except KeyboardInterrupt:
            LOG.info("Interrupted, exiting cleanly")
            return
        except Exception as e:
            LOG.exception(f"Loop error (continuing): {e}")
            time.sleep(MAX_BACKOFF_SEC)


if __name__ == "__main__":
    main()
